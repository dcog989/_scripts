#!/usr/bin/env bash
# health-check.sh - report potential system-wide issues.
#
# Read-only health report. By default only sections with findings are printed;
# known-benign log/package noise is suppressed (see IGNORE_FILE). Use -v to
# dump raw, unfiltered output for every check.
#
# Covers: failed systemd units, pacman database/files/orphans, paccheck
# integrity, boot and kernel journal errors, dmesg err/warn, Btrfs device
# stats + scrub, and disk SMART health. Privileged checks use sudo when
# available and are skipped otherwise.
#
# Exit: 0 no issues, 1 issues found, 2 usage error.
set -uo pipefail

MAX_LINES="${MAX_LINES:-25}"

QUICK=0
VERBOSE=0
FILTER=1
USE_SUDO=1

# Lines matching any pattern (extended regex) are suppressed. Defaults target
# known chatter on this workstation; add machine-specific noise to IGNORE_FILE
# (one regex per line, '#' comments).
DEFAULT_IGNORE=(
  # failures generated by this script's own privilege probe
  'a password is required ;'
  # benign kernel/boot notices
  'TDX not supported by the host platform'
  'amdgpu: Overdrive is enabled'
  # common firmware/ACPI chatter
  'ACPI BIOS Error \(bug\)'
  'ACPI Error: .*No such device'
  # package paths legitimately absent until a service first runs
  ' /var/cache/'
  ' /var/spool/'
  ' /var/named/'
  ' /var/lib/nfs/'
  ' /run/'
  ' /tmp/'
  '/boot/amd-ucode\.img'
)
IGNORE_FILE="${HEALTH_CHECK_IGNORE:-${XDG_CONFIG_HOME:-$HOME/.config}/health-check/ignore}"

usage() {
  cat <<'EOF'
health-check.sh - report potential system-wide issues.

Read-only report of failed units, package integrity, log errors, Btrfs health
and SMART. Prints only checks with findings; -v dumps everything.

Usage:
  health-check.sh            full report (prompts for sudo when needed)
  health-check.sh -q         quick: skip the paccheck md5sum sweep
  health-check.sh -v         verbose: raw output, no benign-noise filter
  health-check.sh --no-sudo  skip privileged checks (Btrfs, SMART, dmesg)

Env:
  MAX_LINES=25     max lines shown per findings list
  HEALTH_CHECK_IGNORE  ignore file (default ~/.config/health-check/ignore)
  SMART_DEVICES=   space-separated block devices (default: auto-detect)
  BTRFS_MOUNTS=    space-separated btrfs mountpoints (default: auto-detect)
EOF
}

while [ $# -gt 0 ]; do
  case "$1" in
    -q|--quick) QUICK=1 ;;
    -v|--verbose) VERBOSE=1; FILTER=0 ;;
    --no-sudo)  USE_SUDO=0 ;;
    -h|--help)  usage; exit 0 ;;
    *) printf 'health-check: unknown option: %s\n' "$1" >&2; usage >&2; exit 2 ;;
  esac
  shift
done

problems=0
skipped=0

append() { if [ -n "$1" ]; then printf '%s' "$1"; fi; }

# emit a section only when there is something to show; a non-empty body counts
# as a finding unless a third argument says otherwise (0/1)
finish() {
  local title="$1" body="$2" prob="${3:-auto}" total
  if [ -n "$body" ]; then
    printf '\n=== %s ===\n' "$title"
    total=$(printf '%s\n' "$body" | grep -c . || true)
    printf '%s\n' "$body" | head -n "$MAX_LINES" | sed 's/^/  /'
    [ "$total" -gt "$MAX_LINES" ] && printf '  ... (%d more)\n' "$((total - MAX_LINES))"
  elif [ "$VERBOSE" -eq 1 ]; then
    printf '\n=== %s ===\n  none\n' "$title"
  fi
  case "$prob" in
    auto) [ -n "$body" ] && problems=$((problems + 1)) ;;
    1)    problems=$((problems + 1)) ;;
  esac
}

# strip lines matching the ignore list (no-op in verbose mode)
purge() {
  if [ "$FILTER" -eq 1 ] && [ -n "$IGNORE_RE" ]; then
    grep -Ev "$IGNORE_RE" || true
  else
    cat
  fi
}

build_ignore_re() {
  local pats=("${DEFAULT_IGNORE[@]}") line
  if [ -f "$IGNORE_FILE" ]; then
    while IFS= read -r line; do
      line="${line%%#*}"
      [ -n "${line//[[:space:]]/}" ] && pats+=("$line")
    done < "$IGNORE_FILE"
  fi
  local IFS='|'
  printf '%s' "${pats[*]}"
}
IGNORE_RE="$(build_ignore_re)"

# --- privilege handling -----------------------------------------------------
SUDO=""
if [ "$(id -u)" -ne 0 ] && command -v sudo >/dev/null 2>&1; then
  SUDO="sudo"
fi

PRIV=0
if [ "$USE_SUDO" -eq 1 ]; then
  if [ "$(id -u)" -eq 0 ]; then
    PRIV=1
  elif [ -n "$SUDO" ] && sudo -n true 2>/dev/null; then
    PRIV=1
  elif [ -n "$SUDO" ] && [ -t 0 ] && sudo -v 2>/dev/null; then
    PRIV=1
  fi
fi

run_priv() { if [ -z "$SUDO" ]; then "$@"; else "$SUDO" "$@"; fi }

# --- header -----------------------------------------------------------------
printf 'health-check: %s  kernel %s  %s\n' "$(hostname)" "$(uname -r)" "$(date '+%Y-%m-%d %H:%M %z')"
[ "$PRIV" -ne 1 ] && printf 'unprivileged: Btrfs, SMART and dmesg checks will be skipped\n'

# --- failed units -----------------------------------------------------------
if command -v systemctl >/dev/null 2>&1; then
  body=""
  sys_failed=$(SYSTEMD_COLORS=0 systemctl --failed --no-legend --no-pager --plain 2>/dev/null || true)
  [ -n "$sys_failed" ] && body="system units:"$'\n'"$sys_failed"
  if [ "$(id -u)" -ne 0 ] && [ -n "${XDG_RUNTIME_DIR:-}" ]; then
    usr_failed=$(SYSTEMD_COLORS=0 systemctl --user --failed --no-legend --no-pager --plain 2>/dev/null || true)
    if [ -n "$usr_failed" ]; then
      body="$(append "$body")${body:+$'\n\n'}user units:"$'\n'"$usr_failed"
    fi
  fi
  finish "Failed systemd units" "$body"
else
  skipped=$((skipped + 1))
fi

# --- package database -------------------------------------------------------
if command -v pacman >/dev/null 2>&1; then
  if out=$(pacman -Dk 2>&1); then db_body=""; else db_body="$out"; fi
  finish "Package database (pacman -Dk)" "$db_body"
fi

# --- package files ----------------------------------------------------------
if command -v pacman >/dev/null 2>&1; then
  raw=$(pacman -Qkq 2>&1 || true)
  finding=$(printf '%s\n' "$raw" | purge)
  finish "Missing package files (pacman -Qkq)" "$finding"
fi

# --- orphans ----------------------------------------------------------------
if command -v pacman >/dev/null 2>&1; then
  raw=$(pacman -Qtdq 2>/dev/null || true)
  finish "Orphan packages (pacman -Qtdq)" "$raw"
fi

# --- paccheck ---------------------------------------------------------------
if command -v paccheck >/dev/null 2>&1; then
  pc=(--files --quiet)
  [ "$QUICK" -eq 0 ] && pc=(--md5sum "${pc[@]}")
  if [ "$PRIV" -eq 1 ]; then
    out=$(run_priv paccheck "${pc[@]}" 2>&1) || true
  else
    out=$(paccheck "${pc[@]}" 2>&1) || true
  fi
  if [ "$PRIV" -eq 0 ]; then
    out=$(printf '%s\n' "$out" | grep -v 'read error (Permission denied)' || true)
  fi
  finish "Package integrity (paccheck ${pc[*]})" "$out"
else
  skipped=$((skipped + 1))
fi

# --- journal ----------------------------------------------------------------
if command -v journalctl >/dev/null 2>&1; then
  raw=$(journalctl -b -p err --no-pager -q 2>/dev/null || true)
  finding=$(printf '%s\n' "$raw" | purge)
  finish "Journal errors this boot" "$([ "$VERBOSE" -eq 1 ] && printf '%s' "$raw" || printf '%s' "$finding")" \
    "$([ -n "$finding" ] && echo 1 || echo 0)"

  raw=$(journalctl -k -b -p err --no-pager -q 2>/dev/null || true)
  finding=$(printf '%s\n' "$raw" | purge)
  finish "Kernel errors this boot" "$([ "$VERBOSE" -eq 1 ] && printf '%s' "$raw" || printf '%s' "$finding")" \
    "$([ -n "$finding" ] && echo 1 || echo 0)"
else
  skipped=$((skipped + 1))
fi

# --- dmesg ------------------------------------------------------------------
if [ "$PRIV" -ne 1 ]; then
  skipped=$((skipped + 1))
elif command -v dmesg >/dev/null 2>&1; then
  raw=$(run_priv dmesg --level=err,warn 2>&1 || true)
  finding=$(printf '%s\n' "$raw" | purge)
  finish "dmesg err/warn" "$([ "$VERBOSE" -eq 1 ] && printf '%s' "$raw" || printf '%s' "$finding")" \
    "$([ -n "$finding" ] && echo 1 || echo 0)"
else
  skipped=$((skipped + 1))
fi

# --- btrfs ------------------------------------------------------------------
BTRFS_MOUNTS="${BTRFS_MOUNTS:-}"
if [ -z "$BTRFS_MOUNTS" ] && command -v findmnt >/dev/null 2>&1; then
  BTRFS_MOUNTS=$(findmnt -t btrfs -o TARGET,SOURCE -rn 2>/dev/null | awk '!seen[$2]++ {print $1}')
fi

if [ -z "$BTRFS_MOUNTS" ]; then
  :
elif [ "$PRIV" -ne 1 ] || ! command -v btrfs >/dev/null 2>&1; then
  skipped=$((skipped + 1))
else
  body=""
  for mp in $BTRFS_MOUNTS; do
    if out=$(run_priv btrfs device stats "$mp" 2>&1); then
      bad=$(printf '%s\n' "$out" | awk '$NF + 0 != 0')
      if [ -n "$bad" ]; then
        body="$(append "$body")${body:+$'\n\n'}$mp:"$'\n'"$bad"
      elif [ "$VERBOSE" -eq 1 ]; then
        body="$(append "$body")${body:+$'\n\n'}$mp:"$'\n'"$out"
      fi
    else
      body="$(append "$body")${body:+$'\n\n'}$mp: error:"$'\n'"$out"
    fi
  done
  finish "Btrfs device stats" "$body"

  body=""
  for mp in $BTRFS_MOUNTS; do
    out=$(run_priv btrfs scrub status -R "$mp" 2>&1 || true)
    es=$(printf '%s\n' "$out" | grep -m1 -i 'Error summary' || true)
    bad=0
    [ -n "$es" ] && printf '%s' "$es" | awk '{for (i = 1; i <= NF; i++) {split($i, a, "="); if (a[2] + 0 > 0) f = 1}} END {exit !f}' && bad=1
    if [ "$bad" -eq 1 ]; then
      body="$(append "$body")${body:+$'\n\n'}$mp: $es"
    elif [ "$VERBOSE" -eq 1 ]; then
      body="$(append "$body")${body:+$'\n\n'}$mp:"$'\n'"$out"
    fi
  done
  finish "Btrfs scrub status" "$body"
fi

# --- smart ------------------------------------------------------------------
SMART_DEVICES="${SMART_DEVICES:-}"
if [ -z "$SMART_DEVICES" ] && command -v lsblk >/dev/null 2>&1; then
  SMART_DEVICES=$(lsblk -dno NAME,TYPE 2>/dev/null | awk '$2 == "disk" && $1 !~ /^(zram|loop|dm-|md)/ {print $1}')
fi

if [ -z "$SMART_DEVICES" ]; then
  :
elif [ "$PRIV" -ne 1 ] || ! command -v smartctl >/dev/null 2>&1; then
  skipped=$((skipped + 1))
else
  body="" bad=0
  for dev in $SMART_DEVICES; do
    [ "${dev#/dev/}" = "$dev" ] && dev="/dev/$dev"
    info=$(run_priv smartctl -H "$dev" 2>&1 || true)
    health=$(printf '%s\n' "$info" | awk -F': *' 'tolower($1) ~ /overall-health self-assessment test result/ {print $2; exit}')
    attrs=$(run_priv smartctl -A "$dev" 2>&1 || true)
    crit=$(printf '%s\n' "$attrs" | grep -Ei 'Reallocated_Sector_Ct|Current_Pending_Sector|Offline_Uncorrectable|Reported_Uncorrect|Media and Data Integrity Errors|Error Information Log Entries|Percentage Used|Available Spare' || true)
    counters_bad=0
    printf '%s\n' "$attrs" | awk '/Media and Data Integrity Errors|Error Information Log Entries|Reallocated_Sector_Ct|Current_Pending_Sector|Offline_Uncorrectable|Reported_Uncorrect/ {if ($NF + 0 > 0) f = 1} END {exit !f}' && counters_bad=1

    case "$health" in
      "")      verdict=unavailable ;;
      PASSED*) verdict=PASSED ;;
      *)       verdict="$health"; bad=1 ;;
    esac
    [ "$counters_bad" -eq 1 ] && bad=1

    if [ "$bad" -eq 1 ]; then
      body="$(append "$body")${body:+$'\n\n'}$dev: $verdict"
      [ -n "$crit" ] && body="$body"$'\n'"$crit"
      [ "$counters_bad" -eq 1 ] && body="$body"$'\n'"nonzero drive error counters"
    elif [ "$VERBOSE" -eq 1 ]; then
      body="$(append "$body")${body:+$'\n\n'}$dev: $verdict"
      [ -n "$crit" ] && body="$body"$'\n'"$crit"
    fi
  done
  finish "Disk SMART" "$body" "$bad"
fi

# --- summary ----------------------------------------------------------------
printf '\n=== summary ===\n'
if [ "$problems" -eq 0 ]; then
  printf '  no issues detected\n'
else
  printf '  %d issue group(s) detected\n' "$problems"
fi
[ "$skipped" -gt 0 ] && printf '  %d check(s) skipped%s\n' "$skipped" \
  "$([ "$PRIV" -eq 1 ] && printf '' || printf ' (unprivileged)')"
[ "$FILTER" -eq 1 ] && printf '  noise filtered; rerun with -v for raw output\n'

[ "$problems" -eq 0 ] && exit 0 || exit 1
